def select_sample(df, condition, fallback_idx=0):
    matches = df[condition(df)]
    if matches.empty:
        return df.iloc[fallback_idx]
    return matches.iloc[0]


@st.cache_data
def build_sample_transactions(df):
    sample_cols = [
        "Time", "Sender_account", "Receiver_account", "Amount",
        "Payment_currency", "Received_currency",
        "Sender_bank_location", "Receiver_bank_location",
        "Payment_type", "Is_laundering"
    ]
    sample_df = df[sample_cols].copy()
    sample_df["Time"] = pd.to_datetime(sample_df["Time"], format="%H:%M:%S", errors="coerce")
    sample_df = sample_df.dropna(subset=["Time"])
    sample_df["hour"] = sample_df["Time"].dt.hour.astype(int)
    sample_df["is_cross_border"] = (
        sample_df["Sender_bank_location"] != sample_df["Receiver_bank_location"]
    ).astype(int)
    sample_df["is_currency_mismatch"] = (
        sample_df["Payment_currency"] != sample_df["Received_currency"]
    ).astype(int)
    sample_df["fan_out_count"] = sample_df.groupby("Sender_account")["Receiver_account"].transform("nunique")
    sample_df["fan_in_count"] = sample_df.groupby("Receiver_account")["Sender_account"].transform("nunique")

    fan_in = sample_df["fan_in_count"] >= 3
    fan_out = sample_df["fan_out_count"] >= 3
    sample_df["Transaction Pattern"] = np.select(
        [
            fan_in & ~fan_out,
            fan_out & ~fan_in,
            fan_in & fan_out,
        ],
        ["fan_in", "fan_out", "fan_in_out"],
        default="normal_flow",
    )

    normal = select_sample(
        sample_df,
        lambda x: (
            (x["Is_laundering"] == 0)
            & (x["is_cross_border"] == 0)
            & (x["is_currency_mismatch"] == 0)
        ),
    )
    cross_border = select_sample(
        sample_df,
        lambda x: (x["is_cross_border"] == 1) | (x["is_currency_mismatch"] == 1),
        fallback_idx=1,
    )
    laundering = select_sample(sample_df, lambda x: x["Is_laundering"] == 1, fallback_idx=2)

    samples = {
        "normal": normal.to_dict(),
        "cross_border": cross_border.to_dict(),
        "laundering": laundering.to_dict(),
    }
    samples["normal"].update({
        "Sender_name": "Harbour Retail Ltd",
        "Receiver_name": "North Street Grocers",
    })
    samples["cross_border"].update({
        "Sender_name": "Global Horizon Trade",
        "Receiver_name": "Westbridge Imports",
    })
    samples["laundering"].update({
        "Sender_name": "Blue Nile Trading",
        "Receiver_name": "Golden Crescent Exchange",
    })
    return samples


