def apply_kyc_override(current_level, sender_profile, receiver_profile):
    risk_values = [
        str(sender_profile.get("kyc_risk_level", "")).lower(),
        str(receiver_profile.get("kyc_risk_level", "")).lower(),
    ]
    pep_values = [
        str(sender_profile.get("pep_status", "")).lower(),
        str(receiver_profile.get("pep_status", "")).lower(),
    ]
    if "yes" in pep_values and current_level in ["low", "medium", "high"]:
        return "critical"
    if "high" in risk_values and current_level in ["low", "medium"]:
        return "high"
    return current_level


def evaluate_hk_rules(hkd_amount, relationship_status, transfer_category, lang):
    triggered = []
    if relationship_status == "occasional_non_customer" and hkd_amount >= HKD_OCCASIONAL_CDD_THRESHOLD:
        triggered.append({
            "code": "HK_120K_OCCASIONAL_CDD",
            "title": tr("rule_120k_title", lang),
            "action": tr("rule_120k_action", lang),
            "severity": "critical",
        })

    if transfer_category in ["wire_transfer", "virtual_asset_transfer"] and hkd_amount >= HKD_WIRE_VA_THRESHOLD:
        triggered.append({
            "code": "HK_8K_WIRE_VA_RECORD",
            "title": tr("rule_8k_title", lang),
            "action": tr("rule_8k_action", lang),
            "severity": "high",
        })

    return triggered


def apply_rules_override(current_level, triggered_rules):
    if any(rule["severity"] == "critical" for rule in triggered_rules):
        return "critical"
    if triggered_rules and current_level in ["low", "medium"]:
        return "high"
    return current_level


def get_priority_for_level(level, lang, screening_result=None, sender_profile=None, receiver_profile=None):
    now = datetime.now()
    if screening_result and screening_result["status"] == "strong":
        return "T+1", now + timedelta(days=1), tr("sanction_strong_reason", lang)
    if screening_result and screening_result["status"] == "possible":
        return "T+5", now + timedelta(days=5), tr("sanction_possible_reason", lang)
    profiles = [sender_profile or {}, receiver_profile or {}]
    if any(str(profile.get("pep_status", "")).lower() == "yes" for profile in profiles):
        return "T+1", now + timedelta(days=1), tr("kyc_override_reason", lang)
    if any(str(profile.get("kyc_risk_level", "")).lower() == "high" for profile in profiles):
        return "T+5", now + timedelta(days=5), tr("kyc_override_reason", lang)
    if level == "critical":
        return "T+1", now + timedelta(days=1), tr("very_high_model_risk", lang)
    if level == "high":
        return "T+5", now + timedelta(days=5), tr("high_model_risk", lang)
    return "T+5", now + timedelta(days=5), tr("standard_alert", lang)


