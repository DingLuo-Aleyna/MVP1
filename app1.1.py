@st.cache_data
def preprocess_data(df):
    df = df.copy()

    required_cols = [
        "Time", "Date", "Sender_account", "Receiver_account", "Amount",
        "Payment_currency", "Received_currency",
        "Sender_bank_location", "Receiver_bank_location",
        "Payment_type", "Is_laundering", "Laundering_type"
    ]

    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing columns in dataset: {missing_cols}")

    df = df.dropna(subset=["Is_laundering"])
    df["Is_laundering"] = df["Is_laundering"].astype(int)

    df["Time"] = pd.to_datetime(df["Time"], format="%H:%M:%S", errors="coerce")
    df["Date"] = pd.to_datetime(df["Date"], errors="coerce")
    df = df.dropna(subset=["Time", "Date"])

    df["hour"] = df["Time"].dt.hour.astype(int)


    # -------------------------
    # Feature engineering
    # -------------------------
    df["is_cross_border"] = (
        df["Sender_bank_location"] != df["Receiver_bank_location"]
    ).astype(int)

    df["is_currency_mismatch"] = (
        df["Payment_currency"] != df["Received_currency"]
    ).astype(int)

    # -------------------------
    # Account-level graph features
    # -------------------------
    sender_out_degree = df.groupby("Sender_account")["Receiver_account"].transform("nunique")
    receiver_in_degree = df.groupby("Receiver_account")["Sender_account"].transform("nunique")

    df["fan_out_count"] = sender_out_degree
    df["fan_in_count"] = receiver_in_degree

    def map_pattern(row):
        if row["fan_in_count"] >= 3 and row["fan_out_count"] < 3:
            return "fan_in"
        elif row["fan_out_count"] >= 3 and row["fan_in_count"] < 3:
            return "fan_out"
        elif row["fan_in_count"] >= 3 and row["fan_out_count"] >= 3:
            return "fan_in_out"
        return "normal_flow"

    df["Transaction Pattern"] = df.apply(map_pattern, axis=1)

    # -------------------------
    # Sort chronologically
    # -------------------------
    df["txn_datetime"] = pd.to_datetime(
        df["Date"].dt.strftime("%Y-%m-%d") + " " + df["Time"].dt.strftime("%H:%M:%S"),
        errors="coerce"
    )
    df = df.sort_values("txn_datetime").reset_index(drop=True)

    # -------------------------
    # Enhanced feature engineering
    # -------------------------
    # Amount features
    df["log_amount"] = np.log1p(df["Amount"])
    df["is_round_amount"] = ((df["Amount"] % 1000 == 0) | (df["Amount"] % 10000 == 0)).astype(int)

    # Binary risk flags (from data analysis)
    df["is_cash_payment"] = df["Payment_type"].isin(["Cash Deposit", "Cash Withdrawal"]).astype(int)
    high_risk_currencies = ["Moroccan dirham", "Dirham"]
    df["is_high_risk_currency"] = (
        df["Payment_currency"].isin(high_risk_currencies) |
        df["Received_currency"].isin(high_risk_currencies)
    ).astype(int)

    # Cyclical time features
    df["hour_sin"] = np.sin(2 * np.pi * df["hour"] / 24)
    df["hour_cos"] = np.cos(2 * np.pi * df["hour"] / 24)
    df["day_of_week"] = df["Date"].dt.dayofweek
    df["is_weekend"] = (df["day_of_week"] >= 5).astype(int)
    df["is_business_hour"] = ((df["hour"] >= 9) & (df["hour"] <= 17)).astype(int)

    # Account velocity features (approximation via cumulative count)
    df = df.sort_values(["Sender_account", "txn_datetime"])
    df["sender_txn_seq_num"] = df.groupby("Sender_account").cumcount()
    df = df.sort_values(["Receiver_account", "txn_datetime"])
    df["receiver_txn_seq_num"] = df.groupby("Receiver_account").cumcount()
    df = df.sort_values("txn_datetime").reset_index(drop=True)

    # Amount anomaly relative to sender
    sender_stats = df.groupby("Sender_account")["Amount"].agg(["mean", "std"]).reset_index()
    sender_stats.columns = ["Sender_account", "sender_avg_amount", "sender_std_amount"]
    df = df.merge(sender_stats, on="Sender_account", how="left")
    df["amount_zscore_sender"] = (df["Amount"] - df["sender_avg_amount"]) / (df["sender_std_amount"] + 1)
    df["amount_ratio_sender"] = df["Amount"] / (df["sender_avg_amount"] + 1)
    df = df.drop(columns=["sender_avg_amount", "sender_std_amount"])

    # Interaction features
    df["cross_border_x_amount"] = df["is_cross_border"] * df["log_amount"]
    df["currency_mismatch_x_amount"] = df["is_currency_mismatch"] * df["log_amount"]
    df["cross_border_and_mismatch"] = (df["is_cross_border"] * df["is_currency_mismatch"]).astype(int)

    # -------------------------
    # Extract behavioural pattern from Laundering_type (without label leakage)
    # Strip "Normal_" prefix to get pure behavioural pattern;
    # fraud-specific patterns describe observable transaction behaviour
    # -------------------------
    df["laundering_pattern"] = df["Laundering_type"].str.replace(r"^Normal_", "", regex=True)

    # -------------------------
    # Keep target separately
    # -------------------------
    y = df["Is_laundering"].copy()

    # -------------------------
    # Keep account columns for reporting only
    # -------------------------
    report_df = df[["Sender_account", "Receiver_account", "Transaction Pattern"]].copy()
    model_df = df.drop(
        columns=[
            "Time",
            "Date",
            "Sender_account",
            "Receiver_account",
            "Laundering_type",
            "Is_laundering"
        ],
        errors="ignore"
    )

    categorical_cols = [
        "Payment_currency",
        "Received_currency",
        "Sender_bank_location",
        "Receiver_bank_location",
        "Payment_type",
        "Transaction Pattern",
        "laundering_pattern"
    ]

    encoders = {}
    for col in categorical_cols:
        le = LabelEncoder()
        model_df[col] = le.fit_transform(model_df[col].astype(str))
        encoders[col] = le

    for col in model_df.columns:
        model_df[col] = pd.to_numeric(model_df[col], errors="coerce")

    valid_idx = model_df.dropna().index
    model_df = model_df.loc[valid_idx].reset_index(drop=True)
    y = y.loc[valid_idx].reset_index(drop=True)
    report_df = report_df.loc[valid_idx].reset_index(drop=True)

    return model_df, y, report_df, encoders, categorical_cols


