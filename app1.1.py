def normalize_name(value):
    value = str(value).lower()
    value = re.sub(r"[^a-z0-9 ]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def name_similarity(left, right):
    left = normalize_name(left)
    right = normalize_name(right)
    if not left or not right:
        return 0
    if left == right:
        return 100
    return round(SequenceMatcher(None, left, right).ratio() * 100)


def screen_party(party_label, party_name, sanctions_df):
    best = {
        "party": party_label,
        "input_name": party_name,
        "matched_name": "",
        "country": "",
        "list_source": "",
        "risk_type": "",
        "score": 0,
    }

    for _, sanction in sanctions_df.iterrows():
        candidates = [sanction.get("name", ""), sanction.get("alias", "")]
        score = max(name_similarity(party_name, candidate) for candidate in candidates)
        if score > best["score"]:
            best.update({
                "matched_name": sanction.get("name", ""),
                "country": sanction.get("country", ""),
                "list_source": sanction.get("list_source", ""),
                "risk_type": sanction.get("risk_type", ""),
                "score": score,
            })

    return best


def screen_sanctions(sender_name, receiver_name, sanctions_df):
    sender_match = screen_party("sender", sender_name, sanctions_df)
    receiver_match = screen_party("receiver", receiver_name, sanctions_df)
    best_match = max([sender_match, receiver_match], key=lambda item: item["score"])

    if best_match["score"] >= SANCTION_STRONG_MATCH_THRESHOLD:
        status = "strong"
    elif best_match["score"] >= SANCTION_POSSIBLE_MATCH_THRESHOLD:
        status = "possible"
    else:
        status = "none"

    return {
        "status": status,
        "best_match": best_match,
        "all_matches": [sender_match, receiver_match],
    }


