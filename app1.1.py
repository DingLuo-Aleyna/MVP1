def get_kyc_profile(account_id, kyc_df):
    matches = kyc_df[kyc_df["account_id"].astype(str) == str(account_id)]
    if matches.empty:
        return {
            "account_id": str(account_id),
            "customer_id": "N/A",
            "legal_name": "",
            "customer_type": "N/A",
            "country": "N/A",
            "industry": "N/A",
            "kyc_risk_level": "Unknown",
            "pep_status": "Unknown",
            "onboarding_date": "N/A",
            "expected_monthly_volume": "N/A",
            "profile_found": False,
        }
    profile = matches.iloc[0].to_dict()
    profile["profile_found"] = True
    return profile


