@st.cache_resource
def train_model(model_df, y):
    full_df = model_df.copy()
    full_df["target"] = y

    # -------------------------
    # Time-based train/validation/test split (60/20/20)
    # -------------------------
    train_df, test_df = train_test_split(
        full_df,
        test_size=0.2,
        stratify=full_df["target"],
        random_state=42
    )

    fit_df, calibration_df = train_test_split(
        train_df,
        test_size=0.25,
        stratify=train_df["target"],
        random_state=42
    )

    # Cap calibration set for efficiency
    if len(calibration_df) > 100000:
        _, calibration_df = train_test_split(
            calibration_df,
            test_size=100000,
            stratify=calibration_df["target"],
            random_state=42
        )

    # Split fit_df into actual train and validation for early stopping
    fit_df, val_df = train_test_split(
        fit_df,
        test_size=0.15,
        stratify=fit_df["target"],
        random_state=42
    )

    # -------------------------
    # Target Encoding (smoothed fraud rate per category)
    # Computed ONLY on fit_df to prevent data leakage
    # -------------------------
    TARGET_ENCODE_COLS = [
        "Payment_currency", "Received_currency",
        "Sender_bank_location", "Receiver_bank_location",
        "Payment_type", "laundering_pattern"
    ]
    SMOOTHING = 100
    global_fraud_rate = fit_df["target"].mean()

    target_encodings = {}
    for col in TARGET_ENCODE_COLS:
        if col not in fit_df.columns:
            continue
        stats = fit_df.groupby(col)["target"].agg(["count", "mean"])
        stats["smoothed_rate"] = (
            (stats["count"] * stats["mean"] + SMOOTHING * global_fraud_rate)
            / (stats["count"] + SMOOTHING)
        )
        target_encodings[col] = stats["smoothed_rate"].to_dict()

    def apply_target_encoding(df, encodings, suffix="_risk"):
        df = df.copy()
        for col, mapping in encodings.items():
            if col in df.columns:
                df[f"{col}{suffix}"] = df[col].map(mapping).fillna(global_fraud_rate)
        return df

    fit_df = apply_target_encoding(fit_df, target_encodings)
    val_df = apply_target_encoding(val_df, target_encodings)
    calibration_df = apply_target_encoding(calibration_df, target_encodings)
    test_df = apply_target_encoding(test_df, target_encodings)

    # -------------------------
    # Improved sampling: 15:1 ratio (was 1:1, then capped at 5000)
    # -------------------------
    train_majority = fit_df[fit_df["target"] == 0]
    train_minority = fit_df[fit_df["target"] == 1]

    SAMPLING_RATIO = 15  # normal:fraud ratio after undersampling
    target_normal_count = min(len(train_majority), len(train_minority) * SAMPLING_RATIO)

    train_majority_downsampled = resample(
        train_majority,
        replace=False,
        n_samples=target_normal_count,
        random_state=42
    )

    train_balanced = pd.concat([train_majority_downsampled, train_minority])
    # NO MORE 5000-sample cap — we use all available data

    X_train = train_balanced.drop("target", axis=1)
    y_train = train_balanced["target"]

    X_val = val_df.drop("target", axis=1)
    y_val = val_df["target"]

    X_test = test_df.drop("target", axis=1)
    y_test = test_df["target"]

    # -------------------------
    # Improved XGBoost with scale_pos_weight + early stopping
    # -------------------------
    # Load tuned params if available, otherwise use defaults
    import json as _json
    if BEST_PARAMS_PATH.exists():
        with BEST_PARAMS_PATH.open("r", encoding="utf-8") as _f:
            tuned_params = _json.load(_f)
    else:
        tuned_params = {}

    xgb_params = {
        "n_estimators": tuned_params.get("n_estimators", 300),
        "max_depth": tuned_params.get("max_depth", 6),
        "learning_rate": tuned_params.get("learning_rate", 0.05),
        "subsample": tuned_params.get("subsample", 0.8),
        "colsample_bytree": tuned_params.get("colsample_bytree", 0.8),
        "min_child_weight": tuned_params.get("min_child_weight", 3),
        "reg_alpha": tuned_params.get("reg_alpha", 0.1),
        "reg_lambda": tuned_params.get("reg_lambda", 0.1),
        "scale_pos_weight": tuned_params.get("scale_pos_weight", SAMPLING_RATIO),
        "n_jobs": -1,
        "eval_metric": "aucpr",
        "tree_method": "hist",
        "random_state": 42
    }

    model = XGBClassifier(**xgb_params)

    model.fit(
        X_train, y_train,
        eval_set=[(X_val, y_val)],
        verbose=False
    )

    # -------------------------
    # Probability calibration
    # -------------------------
    X_calibration = calibration_df.drop("target", axis=1)
    y_calibration = calibration_df["target"]

    scoring_model = CalibratedClassifierCV(
        estimator=model,
        method="sigmoid",
        cv=5
    )
    scoring_model.fit(X_calibration, y_calibration)

    # -------------------------
    # Evaluation metrics
    # -------------------------
    calibrated_scores = scoring_model.predict_proba(X_test)[:, 1]
    y_pred = (calibrated_scores >= DEFAULT_ALERT_THRESHOLD).astype(int)

    auprc = average_precision_score(y_test, calibrated_scores)

    # Alert rate: what % of transactions would be flagged at DEFAULT_ALERT_THRESHOLD
    alert_rate = y_pred.mean() * 100

    metrics = {
        "train_distribution": train_balanced["target"].value_counts().to_dict(),
        "calibration_distribution": calibration_df["target"].value_counts().to_dict(),
        "test_distribution": test_df["target"].value_counts().to_dict(),
        "recall": recall_score(y_test, y_pred),
        "precision": precision_score(y_test, y_pred, zero_division=0),
        "f1": f1_score(y_test, y_pred, zero_division=0),
        "auprc": auprc,
        "alert_rate": alert_rate,
        "num_train_samples": len(train_balanced),
        "classification_report": classification_report(y_test, y_pred, zero_division=0),
        "calibration_method": "Sigmoid probability calibration on a holdout set",
        "evaluation_threshold": DEFAULT_ALERT_THRESHOLD,
        "sampling_ratio": SAMPLING_RATIO
    }

    return model, scoring_model, X_train, X_test, y_test, metrics


